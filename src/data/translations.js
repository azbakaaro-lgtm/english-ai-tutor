export function t(lang, path) {
  const parts = path.split(".");
  let node = translations[lang] || translations.en;
  for (const p of parts) {
    node = node?.[p];
    if (node === undefined) break;
  }
  if (node === undefined) {
    // fallback to English
    node = translations.en;
    for (const p of parts) node = node?.[p];
  }
  return node ?? path;
}
